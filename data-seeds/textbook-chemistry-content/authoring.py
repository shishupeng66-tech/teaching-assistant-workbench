POINTS = []


def P(code, node, name, definition, requirements, mastery, *questions):
    assert len(questions) == 3
    POINTS.append(
        dict(
            code=code,
            node=node,
            name=name,
            definition=definition,
            requirements=requirements,
            mastery=mastery,
            questions=list(questions),
        )
    )


def C(prompt, options, answer, explanation, difficulty=1):
    return dict(
        type="单选题",
        difficulty=difficulty,
        prompt=prompt,
        options=options,
        answer=answer,
        explanation=explanation,
    )


def S(prompt, answer, explanation, difficulty=2, kind="简答题", check=None):
    return dict(
        type=kind,
        difficulty=difficulty,
        prompt=prompt,
        answer=answer,
        explanation=explanation,
        check=check,
    )


